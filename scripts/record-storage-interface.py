#!/usr/bin/env python3
"""Record the original IOBlockStorageDevice interface of the pinned kernelcache from public inputs.

build-native-virtio-bindings.py binds NativeVirtioBlock, NativeRamBlock and NativeMsdc to the original
IOBlockStorageDevice of IOStorageFamily. Its full audit, audit-storage-interface.py, reads a prelinked candidate kernel,
a debugger snapshot of that kernel and the AES audit. This script derives the values the bindings use without them:

* the dispatch table shape and the reference name of every slot, from IOBlockStorageDevice.cpp of the public
  IOStorageFamily source compiled against the public xnu headers (the object is inspected, never linked or run);
* the original addresses, from the kernelcache that board.toml pins: the unique table whose kernel slots hold the
  kernel exports of those names, the protected constructor, the base destructor, the abstract D1/D0 traps, the
  metaclass getter and the static metaclass registration (class name, IOService parent, instance size);
* the addresses of the prelinked candidate, by adding the [kernel.prelink] slide, as kits/NativePrelink does for every
  component pointer.

The record, scripts/data/native-storage-interface-audit.json, holds addresses and symbol names only. With --check the
script recomputes it and fails when the committed record differs.

    ./unixnu fetch -D ../UniXNU-<device> && ./unixnu tree -D ../UniXNU-<device>
    ./unixnu ipsw fetch KernelCache -D ../UniXNU-<device>
    python3 scripts/record-storage-interface.py --board ../UniXNU-<device>/board.toml \
        --kernelcache out/ipsw/<build>/kernelcache.decompressed \
        --xnu out/<device>/tree/refer/xnu --iostoragefamily out/<device>/tree/refer/IOStorageFamily [--check]
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import struct
import subprocess
import sys
import tempfile
import tomllib

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'kits/NativePrelink'))
import native_prelink as np  # noqa: E402

IOSTORAGEFAMILY_REVISION = 'e45fbe30a7879e0b16e26dddb78538f1b00e0bff'
STORAGE_MODULE = 'com.apple.iokit.IOStorageFamily'
CLASS = 'IOBlockStorageDevice'
# Headers that the xnu build generates and the source tree lacks. The MIG interfaces (mach/*.h) declare C routines only.
# The DriverKit headers are generated by iig and provide <Class>_Methods / <Class>_KernelMethods; those macros are
# defined below from the kernelcache exports. Neither contributes data members or other virtual methods, which the
# slot-by-slot comparison with the kernelcache confirms.
GENERATED = ['mach/clock.h', 'mach/clock_priv.h', 'mach/clock_reply_server.h', 'mach/exc_server.h', 'mach/host_priv.h',
             'mach/host_security.h', 'mach/mach_exc_server.h', 'mach/mach_host.h', 'mach/mach_port.h',
             'mach/notify_server.h', 'mach/processor.h', 'mach/processor_set.h', 'mach/task.h', 'mach/thread_act.h',
             'mach/vm_map.h', 'DriverKit/OSObject.h', 'DriverKit/IOMemoryDescriptor.h', 'DriverKit/IOMemoryMap.h',
             'DriverKit/IOService.h', 'DriverKit/IOUserClient.h']
IIG_CLASSES = ['OSObject', 'IOService', 'IOUserClient', 'IOMemoryDescriptor', 'IOMemoryMap']
# The platform-selection header of an iOS device target (the source kernel SDK does not carry it).
TARGET_CONDITIONALS = {'MAC': 1, 'WIN32': 0, 'UNIX': 0, 'LINUX': 0, 'OSX': 0, 'IPHONE': 1, 'IOS': 1, 'WATCH': 0, 'TV': 0,
                       'MACCATALYST': 0, 'UIKITFORMAC': 0, 'SIMULATOR': 0, 'EMBEDDED': 1, 'RTKIT': 0, 'DRIVERKIT': 0,
                       'BRIDGE': 0, 'VISION': 0, 'XR': 0, 'NANO': 0}
BRK_1 = 0xd4200020


def fail(message):
    raise SystemExit('record-storage-interface: ' + message)


def require(value, message):
    if not value:
        fail(message)


def revision(path):
    return subprocess.check_output(['git', '-C', path, 'rev-parse', 'HEAD'], text=True).strip()


def feed_commit(name):
    feeds = tomllib.loads((ROOT / 'feeds.toml').read_text())
    return next(source['commit'] for source in feeds['source'] if source['name'] == name)


def compiler():
    found = shutil.which('clang')
    if found:
        return [found]
    if shutil.which('xcrun'):
        return ['xcrun', 'clang']
    fail('clang not found')


def compile_reference(xnu, storage, work, kernel_exports):
    """Compile the public source; return the reference object bytes and the macros used for the iig classes."""
    include = work / 'include'
    (include / 'IOKit/storage').mkdir(parents=True)
    for header in storage.glob('*.h'):
        shutil.copyfile(header, include / 'IOKit/storage' / header.name)
    (include / 'TargetConditionals.h').write_text(
        '#pragma once\n' + ''.join(f'#define TARGET_OS_{k} {v}\n' for k, v in TARGET_CONDITIONALS.items()) +
        '#define TARGET_IPHONE_SIMULATOR 0\n#define TARGET_CPU_ARM64 1\n#define TARGET_CPU_ARM 0\n#define TARGET_CPU_X86 0\n'
        '#define TARGET_CPU_X86_64 0\n#define TARGET_CPU_PPC 0\n#define TARGET_CPU_PPC64 0\n#define TARGET_CPU_68K 0\n'
        '#define TARGET_RT_MAC_MACHO 1\n#define TARGET_RT_LITTLE_ENDIAN 1\n#define TARGET_RT_BIG_ENDIAN 0\n'
        '#define TARGET_RT_64_BIT 1\n')
    generated = work / 'generated'
    for name in GENERATED:
        (generated / name).parent.mkdir(parents=True, exist_ok=True)
        (generated / name).write_text('/* generated by the xnu build; not needed for the class layout */\n')
    # iig declares the Dispatch override in <Class>_Methods of every class that has one; the kernel exports it.
    macros = {}
    for name in IIG_CLASSES:
        exported = f'__ZN{len(name)}{name}8DispatchE5IORPC' in kernel_exports
        macros[name + '_Methods'] = 'virtual kern_return_t Dispatch(const IORPC rpc) APPLE_KEXT_OVERRIDE;' if exported else ''
        macros[name + '_KernelMethods'] = ''
    flags = ['-target', 'arm64-apple-ios17.0', '-std=gnu++2a', '-fapple-kext', '-mkernel', '-nostdinc', '-nostdinc++',
             '-fno-builtin', '-fno-exceptions', '-fno-rtti', '-DKERNEL', '-DAPPLE', '-DNeXT',
             '-Wno-deprecated-declarations', *[f'-D{k}={v}' for k, v in macros.items()],
             '-I', include, *[x for d in ('iokit', 'libkern', 'bsd', 'osfmk', 'osfmk/libsa', 'pexpert', 'EXTERNAL_HEADERS')
                               for x in ('-I', xnu / d)], '-I', generated]
    sizes = work / 'sizes.cpp'
    sizes.write_text('#include <IOKit/storage/IOBlockStorageDevice.h>\n'
                     'static_assert(sizeof(IOBlockStorageDevice) == 0x90, "public IOBlockStorageDevice size");\n'
                     'static_assert(sizeof(IOService) == 0x88, "public IOService size");\n')
    for source, output in ((storage / 'IOBlockStorageDevice.cpp', work / 'reference.o'), (sizes, work / 'sizes.o')):
        r = subprocess.run(compiler() + [str(f) for f in flags] + ['-c', str(source), '-o', str(output)],
                           capture_output=True, text=True)
        if r.returncode:
            fail('compiling the public source failed:\n' + (r.stdout + r.stderr)[-3000:])
    return (work / 'reference.o').read_bytes(), macros


def reference_slots(obj):
    """The 190 relocated dispatch slots of the compiled class, as in audit-storage-interface.py."""
    om = np.macho(obj)
    require(om['kind'] == 1, 'expected an ARM64 relocatable reference object')
    sycmd = next(at for command, at, size in om['commands'] if command == 2)
    symoff, count, stroff, _ = struct.unpack_from('<4I', obj, sycmd + 8)
    symbols = []
    for i in range(count):
        ix, kind, _, _, value = struct.unpack_from('<IBBHQ', obj, symoff + i * 16)
        symbols.append(dict(name=obj[stroff + ix:obj.index(b'\0', stroff + ix)].decode(), value=value, kind=kind))
    vtable = next(s['value'] for s in symbols if s['name'] == f'__ZTV{len(CLASS)}{CLASS}')
    end = min(s['value'] for s in symbols if not s['kind'] & 0xe0 and s['kind'] & 0xe == 0xe and s['value'] > vtable)
    relocations = {}
    for segment in om['segments']:
        for section in segment['sections']:
            if section['va'] <= vtable < section['va'] + section['size']:
                ro, rc = struct.unpack_from('<II', obj, section['command_offset'] + 56)
                for i in range(rc):
                    address, word = struct.unpack_from('<II', obj, ro + i * 8)
                    if word >> 27 & 1 and word >> 28 == 0 and word >> 25 & 3 == 3:
                        relocations[section['va'] + address] = symbols[word & 0xffffff]['name']
    methods = []
    for at in range(vtable + 16, end, 8):
        if at not in relocations:
            break
        methods.append(relocations[at])
    require(len(methods) == 190 and methods.count('___cxa_pure_virtual') == 14, 'public iOS class dispatch shape changed')
    return methods


def signed(value, bits):
    return value - (1 << bits) if value & 1 << (bits - 1) else value


def adrp(address, word):
    require(word & 0x9f000000 == 0x90000000, f'expected adrp at {address:#x}')
    return (address & ~4095) + signed(((word >> 5 & 0x7ffff) << 2) | (word >> 29 & 3), 21) * 4096


def branch(address, word):
    return address + signed(word & 0x3ffffff, 26) * 4


class Kernelcache:
    def __init__(self, data):
        self.data = data
        self.image = np.macho(data)
        self.exports = np.exports(data, self.image)
        self.by_name = {name: va for va, names in self.exports.items() for name in names}
        info = next(s for s in self.image['segments'] if s['name'] == '__PRELINK_INFO')
        at = np.backed_offset(self.image['segments'], info['va'], info['filesize'], len(data))
        entries = np.unserialize_xml(data[at:at + info['filesize']])['_PrelinkInfoDictionary']
        entry = next(e for e in entries if e['CFBundleIdentifier'] == STORAGE_MODULE)
        header = np.backed_offset(self.image['segments'], entry['_PrelinkExecutableLoadAddr'], 32, len(data))
        module = np.macho(data, header)
        require(module['kind'] == 11, 'IOStorageFamily is not a prelinked kext bundle')
        self.segments = {s['name']: (s['va'], s['size']) for s in module['segments']}

    def read(self, va, length):
        at = np.backed_offset(self.image['segments'], va, length, len(self.data))
        return self.data[at:at + length]

    def word(self, va):
        return struct.unpack('<I', self.read(va, 4))[0]

    def words(self, va, count):
        return struct.unpack(f'<{count}I', self.read(va, count * 4))

    def quad(self, va):
        return struct.unpack('<Q', self.read(va, 8))[0]

    def inside(self, segment, va):
        start, size = self.segments[segment]
        return start <= va < start + size

    def cstring(self, va):
        blob = self.read(va, 256)
        return blob[:blob.index(b'\0')].decode()

    def stub_names(self, address):
        """Kernel export names reached through an import stub (adrp x16; ldr x16, [x16]; br x16) of the kext."""
        a, load, jump = self.words(address, 3)
        require(a & 0x9f00001f == 0x90000010 and load & 0xffc003ff == 0xf9400210 and jump == 0xd61f0200,
                f'unqualified import stub at {address:#x}')
        return self.exports.get(self.quad(adrp(address, a) + (load >> 10 & 4095) * 8), [])


def page_offset(word, shift):
    return (word >> 10 & 4095) << shift


def analyse(kc, methods):
    text_va, text_size = kc.segments['__TEXT_EXEC']
    const_va, const_size = kc.segments['__DATA_CONST']
    blob = kc.read(const_va, const_size)
    found = []
    for at in range(0, len(blob) - (len(methods) + 2) * 8 + 1, 8):
        if blob[at:at + 16] != bytes(16):
            continue
        pointers = struct.unpack_from('<' + 'Q' * len(methods), blob, at + 16)
        if all(pointers[i] == kc.by_name[name] for i, name in enumerate(methods) if name in kc.by_name):
            found.append((const_va + at, pointers))
    require(len(found) == 1, f'expected one original {CLASS} dispatch table, found {len(found)}')
    table, pointers = found[0]
    bound = [i for i, name in enumerate(methods) if name in kc.by_name]
    require(len(bound) == 176, f'unexpected original kernel binding count {len(bound)}')
    own = [i for i in range(len(methods)) if i not in bound]
    require(all(kc.inside('__TEXT_EXEC', pointers[i]) for i in own), 'owned storage method outside the original text')
    require(all(methods[i].startswith((f'__ZN{len(CLASS)}{CLASS}', f'__ZNK{len(CLASS)}{CLASS}')) for i in own),
            'a slot outside the kernel is not an IOBlockStorageDevice method')
    # The protected constructor: IOService::IOService(meta) then the vptr store of this table.
    constructors = []
    for address in range(text_va, text_va + text_size - 32, 4):
        w = kc.words(address, 8)
        if (w[:2] != (0xa9bf7bfd, 0x910003fd) or w[2] & 0xfc000000 != 0x94000000 or
                w[3] & 0x9f00001f != 0x90000008 or w[4] & 0xffc003ff != 0x91000108 or
                w[5:] != (0xf9000008, 0xa8c17bfd, 0xd65f03c0)):
            continue
        if adrp(address + 12, w[3]) + page_offset(w[4], 0) == table + 16:
            constructors.append((address, branch(address + 8, w[2])))
    require(len(constructors) == 1 and '__ZN9IOServiceC2EPK11OSMetaClass' in kc.stub_names(constructors[0][1]),
            'the original protected constructor does not forward to IOService')
    # D2 is the tail call to IOService::~IOService right before the D1 slot target; D1 and D0 of the abstract class trap.
    destructor = pointers[0] - 4
    word = kc.word(destructor)
    require(word & 0xfc000000 == 0x14000000 and '__ZN9IOServiceD2Ev' in kc.stub_names(branch(destructor, word)),
            'unqualified original base destructor')
    require(kc.word(pointers[0]) == BRK_1 and kc.word(pointers[1]) == BRK_1, 'abstract D1/D0 are not brk #1 traps')
    a, add, ret = kc.words(pointers[7], 3)
    require(a & 0x9f00001f == 0x90000000 and add & 0xffc003ff == 0x91000000 and ret == 0xd65f03c0,
            'unqualified original metaclass getter')
    meta = adrp(pointers[7], a) + page_offset(add, 0)
    # The static metaclass registration: OSMetaClass(meta, "IOBlockStorageDevice", &IOService::gMetaClass, size).
    service_meta = kc.by_name['__ZN9IOService10gMetaClassE']
    registrations = []
    for address in range(text_va, text_va + text_size - 48, 4):
        w = kc.words(address, 11)
        if (w[:2] != (0xa9bf7bfd, 0x910003fd) or w[2] & 0x9f00001f != 0x90000000 or w[3] & 0xffc003ff != 0x91000000 or
                w[4] & 0x9f00001f != 0x90000001 or w[5] & 0xffc003ff != 0x91000021 or
                w[6] & 0x9f00001f != 0x90000002 or w[7] & 0xffc003ff != 0xf9400042 or
                w[8] & 0xffe0001f != 0x52800003 or w[9] & 0xfc000000 != 0x94000000):
            continue
        if adrp(address + 8, w[2]) + page_offset(w[3], 0) != meta:
            continue
        registrations.append(dict(function=address, name=kc.cstring(adrp(address + 16, w[4]) + page_offset(w[5], 0)),
                                  parent=kc.quad(adrp(address + 24, w[6]) + page_offset(w[7], 3)),
                                  size=w[8] >> 5 & 0xffff, call=kc.stub_names(branch(address + 36, w[9]))))
    require(len(registrations) == 1, 'expected one static IOBlockStorageDevice metaclass registration')
    registration = registrations[0]
    require(registration['name'] == CLASS and registration['parent'] == service_meta and registration['size'] == 0x90 and
            '__ZN11OSMetaClassC2EPKcPKS_j' in registration['call'], 'original metaclass registration mismatch')
    # IOService::MetaClass::MetaClass() of the kernel registers the 0x88-byte parent.
    service = kc.by_name['__ZN9IOService9MetaClassC2Ev']
    w = kc.words(service, 8)
    require(w[2] & 0x9f00001f == 0x90000001 and w[3] & 0xffc003ff == 0x91000021 and w[6] == 0x52801103 and
            w[7] & 0xfc000000 == 0x94000000 and
            kc.cstring(adrp(service + 8, w[2]) + page_offset(w[3], 0)) == 'IOService' and
            '__ZN11OSMetaClassC2EPKcPKS_j' in kc.exports.get(branch(service + 28, w[7]), []),
            'original IOService metaclass registration mismatch')
    return dict(table=table, pointers=pointers, own=own, constructor=constructors[0][0], destructor=destructor,
                meta=meta, service_meta=service_meta, registration=registration['function'])


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--board', type=Path, required=True, help='board.toml with [kernel.prelink] kernelcache_sha256 and slide')
    parser.add_argument('--kernelcache', type=Path, required=True, help='the decompressed kernelcache Mach-O')
    parser.add_argument('--xnu', type=Path, default=ROOT / 'refer/xnu')
    parser.add_argument('--iostoragefamily', type=Path, default=ROOT / 'refer/IOStorageFamily')
    parser.add_argument('--output', type=Path, default=ROOT / 'scripts/data/native-storage-interface-audit.json')
    parser.add_argument('--check', action='store_true', help='compare with the existing record instead of writing it')
    args = parser.parse_args()

    prelink = tomllib.loads(args.board.read_text())['kernel']['prelink']
    slide = int(prelink['slide'], 0)
    data = args.kernelcache.read_bytes()
    pinned = hashlib.sha256(data).hexdigest()
    require(pinned == prelink['kernelcache_sha256'], 'the kernelcache does not match the board pin')
    require(revision(args.iostoragefamily) == IOSTORAGEFAMILY_REVISION, 'unexpected public IOStorageFamily revision')
    xnu_revision = revision(args.xnu)
    require(xnu_revision == feed_commit('xnu'), 'the xnu source is not the revision of feeds.toml')

    kc = Kernelcache(data)
    with tempfile.TemporaryDirectory() as work:
        obj, macros = compile_reference(args.xnu, args.iostoragefamily, Path(work), kc.by_name)
    methods = reference_slots(obj)
    found = analyse(kc, methods)
    pointers = found['pointers']
    own = set(found['own'])

    def slid(value):
        return hex(value + slide)

    record = dict(
        description='Original IOBlockStorageDevice interface of the pinned kernelcache, derived statically by '
                    'scripts/record-storage-interface.py. Candidate addresses are the original addresses plus the '
                    'prelink slide. Addresses and symbol names only.',
        kernelcache_sha256=pinned, slide=prelink['slide'], public_source_revision=IOSTORAGEFAMILY_REVISION,
        xnu_revision=xnu_revision,
        source_sha256=hashlib.sha256((args.iostoragefamily / 'IOBlockStorageDevice.cpp').read_bytes()).hexdigest(),
        header_sha256=hashlib.sha256((args.iostoragefamily / 'IOBlockStorageDevice.h').read_bytes()).hexdigest(),
        iig_dispatch_overrides=sorted(k.removesuffix('_Methods') for k, v in macros.items() if v),
        method_slots=len(methods), kernel_bindings=len(methods) - len(own),
        pure_virtual_slots=methods.count('___cxa_pure_virtual'),
        inherited_kernel_methods=len(methods) - len(own) - methods.count('___cxa_pure_virtual'),
        vtable=slid(found['table']), original_metaclass=slid(found['meta']),
        original_protected_constructor=slid(found['constructor']), original_base_destructor=slid(found['destructor']),
        original_metaclass_registration=slid(found['registration']),
        abstract_complete_destructors_trap=True, compiled_public_class_size=0x90,
        metaclass_registration=dict(class_name=CLASS, superclass='__ZN9IOService10gMetaClassE', class_size=0x90,
                                    superclass_size=0x88),
        original_addresses=dict(vtable=hex(found['table']), metaclass=hex(found['meta']),
                                protected_constructor=hex(found['constructor']),
                                base_destructor=hex(found['destructor']), ioservice_metaclass=hex(found['service_meta'])),
        methods=[dict(slot=i, reference_name=name, original_target=hex(pointers[i]),
                      candidate_target=slid(pointers[i]) if i in own else None,
                      kernel_names=[] if i in own else sorted(kc.exports.get(pointers[i], [])))
                 for i, name in enumerate(methods)],
        static_record=True, disk_read_tested=False, transport_implemented=False, hardware_tested=False)
    text = json.dumps(record, indent=2) + '\n'
    if args.check:
        require(args.output.is_file() and args.output.read_text() == text, f'{args.output} differs from the recomputed record')
        print(f'PASS: {args.output.name} matches the kernelcache and the public source')
        return
    args.output.write_text(text)
    print(f'PASS: {len(methods)} slots, {len(methods) - len(own)} kernel bindings, {len(own)} original storage methods')
    print(f'Recorded {args.output}')


if __name__ == '__main__':
    main()
